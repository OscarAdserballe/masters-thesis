exec(open("load.py").read())
X=pd.read_parquet("traces.parquet").dropna(subset=["menu_index"])
X["menu_index"]=X.menu_index.astype(int)
th=pd.read_parquet("users.parquet").rename(columns={f:"t_"+f for f in FEAT})
dthink=held[held.arm=="gemma4-31b-think"][["user_id","checkpoint","menu_index","correct","forced","regret"]]
# cp0 traces are logged under one uid only; expand cp0 to all users
X0=X[X.cp==0].drop(columns="uid").drop_duplicates("menu_index")
X0=X0.merge(pd.DataFrame({"uid":users}),how="cross")
X=pd.concat([X[X.cp>0],X0]).drop_duplicates(["uid","cp","menu_index"],keep="last")
M=X.merge(dthink,left_on=["uid","cp","menu_index"],right_on=["user_id","checkpoint","menu_index"]).merge(th,on="uid")
print("joined",len(M))
def tab(col,bins=None):
    c=M[col] if bins is None else pd.cut(M[col],bins)
    return (M.groupby([c,"cp"]).correct.mean().unstack()*100).round(1)
print("\naccuracy by # norm words (objectively/usually/typically/...) in trace:"); print(tab("norm",[-1,0,1,3,99]))
print("\nshare of traces with norm words, by cp:", (M.groupby("cp").norm.apply(lambda s:(s>0).mean())*100).round(1).to_dict())
print("\naccuracy by trace length (chars):"); print(tab("chars",[0,1500,2500,3500,1e9]))
print("\nmentions per trace by cp (mean counts):"); print(M.groupby("cp")[["dep","dur","stops","price","hyp","wait"]].mean().round(2))

print("\nhypothesis flags by user's true price sign (% of traces), cp>=2:")
M["psign"]=np.sign(M.t_price)
print((M[M.cp>=2].groupby("psign")[["cheaper_better","expensive_ok","contradict"]].mean()*100).round(1))
print("\naccuracy when trace says 'expensive OK' vs not, for users who prefer pricier (cp>=2):")
print((M[(M.cp>=2)&(M.psign>0)].groupby("expensive_ok").correct.mean()*100).round(1))
print("\ndeparture mentions per trace by user's |θ_departure|, cp5:")
print(M[M.cp==5].groupby(M.t_departure.abs()).dep.mean().round(2))
print("\nshare of cp>=1 traces mentioning each attribute at least once:")
print((M[M.cp>=1][["dep","dur","stops","price"]]>0).mean().round(3))
M.to_parquet("traces_joined.parquet")
